import sys, json, subprocess, numpy as np
src, out = sys.argv[1], sys.argv[2]
SR=22050
raw = subprocess.run(['ffmpeg','-v','quiet','-i',src,'-ac','1','-ar',str(SR),'-f','f32le','-'],capture_output=True).stdout
x = np.frombuffer(raw, dtype=np.float32).astype(np.float64)
dur = len(x)/SR
N=1024; H=256; fps=SR/H
win=np.hanning(N)
nfr=1+(len(x)-N)//H
frames=np.lib.stride_tricks.as_strided(x,shape=(nfr,N),strides=(x.strides[0]*H,x.strides[0])).copy()*win
S=np.abs(np.fft.rfft(frames,axis=1))
freqs=np.fft.rfftfreq(N,1/SR)
times=(np.arange(nfr)*H+N/2)/SR
def band(lo,hi): return S[:,(freqs>=lo)&(freqs<hi)]
def flux(B):
    L=np.log1p(100*B); d=np.diff(L,axis=0,prepend=L[:1]); return np.maximum(d,0).sum(1)
def norm(v): v=v-v.min(); return v/(v.max()+1e-9)
low=band(20,150); mid=band(150,2500); high=band(5000,11000)
fl_all=norm(flux(S)); fl_low=norm(flux(low)); fl_mid=norm(flux(mid)); fl_high=norm(flux(high))
rms=np.sqrt((frames**2).mean(1)); rms=norm(rms)
lowE=norm(np.sqrt((low**2).sum(1)))
def smooth(v,k):
    k=max(1,int(k)); return np.convolve(v,np.ones(k)/k,mode='same')
energy=norm(smooth(rms,fps*0.5))
# tempo via autocorr of onset env
oe=fl_all-smooth(fl_all,fps*0.3); oe=np.maximum(oe,0)
ac=np.correlate(oe,oe,'full')[len(oe)-1:]
lags=np.arange(len(ac))/fps
bpms=60/np.maximum(lags,1e-9)
mask=(bpms>=70)&(bpms<=180)
# weight towards 120
w=np.exp(-0.5*(np.log2(bpms/120)/1.0)**2)
cand=np.where(mask)[0]
best=cand[np.argmax(ac[cand]*w[cand])]
bpm=60/lags[best]; period=lags[best]
# beat tracking: DP (Ellis)
pf=period*fps
score=oe.copy(); back=np.full(len(oe),-1)
for i in range(len(oe)):
    lo=int(i-2*pf); hi=int(i-pf/2)
    if hi<=0: continue
    lo=max(lo,0)
    js=np.arange(lo,hi)
    pen=-100*(np.log((i-js)/pf))**2*0.01
    cand_s=score[js]+pen*oe.max()
    k=np.argmax(cand_s); score[i]=oe[i]+cand_s[k]; back[i]=js[k]
i=int(np.argmax(score[-int(pf*2):]))+len(score)-int(pf*2)
beats=[]
while i>=0: beats.append(i); i=back[i]
beats=sorted(beats); beat_t=[round(float(times[b]),3) for b in beats]
# downbeat phase: pick phase (0-3) with max low-band flux
lf=[fl_low[b] for b in beats]
phase=int(np.argmax([np.mean(lf[p::4]) for p in range(4)]))
# onset peak picking per band
def peaks(env,thr,minsep=0.07):
    loc=smooth(env,fps*0.25)
    res=[]; last=-9
    for i in range(1,len(env)-1):
        if env[i]>env[i-1] and env[i]>=env[i+1] and env[i]>loc[i]+thr:
            t=times[i]
            if t-last>=minsep: res.append([round(float(t),3),round(float(env[i]),3)]); last=t
    return res
data=dict(duration=round(dur,3),bpm=round(float(bpm),2),beatPeriod=round(float(period),4),
  beats=beat_t,downbeatPhase=phase,downbeats=beat_t[phase::4],
  kicks=peaks(fl_low,0.12),snares=peaks(fl_mid,0.12),hats=peaks(fl_high,0.1,0.05),onsets=peaks(fl_all,0.1),
  envFps=30)
# 30fps curves
idx=lambda tt: np.clip((tt*fps).astype(int),0,nfr-1)
tt=np.arange(0,dur,1/30)
data['energy']=[round(float(v),3) for v in energy[idx(tt)]]
data['low']=[round(float(v),3) for v in smooth(lowE,fps*0.05)[idx(tt)]]
if out.endswith('.js'):
    open(out,'w').write('// Generated by tools/analyze_beats.py — do not edit by hand.\nwindow.BEATMAP = '+json.dumps(data,separators=(',',':'))+';\n')
else:
    json.dump(data,open(out,'w'))
print('dur',dur,'bpm',bpm,'beats',len(beat_t),'phase',phase)
print('beats',beat_t)
print('downbeats',data['downbeats'])
print('kicks',[k[0] for k in data['kicks']])
print('snares',[k[0] for k in data['snares']])
print('energy@0.5s',[round(float(energy[idx(np.array([t]))][0]),2) for t in np.arange(0,dur,0.5)])
